    /**
     * Generate an entry for a note from another source.
     *
     * @param directory an optional directory in which to put the note.
     * The caller needs to make sure a {@link ZipEntry} is created for
     * this directory.
     * @param note the content of the note to store.  A random name will
     * be generated for the entry.
     *
     * @return a {@link Map.Entry} with the ZIP entry and input stream for
     * the note content.
     */
    private static Map.Entry<ZipEntry,InputStream> makeNoteFile(
            String directory, String note) {
        StringBuilder fileName = new StringBuilder();
        if (directory != null)
            fileName.append(directory);
        fileName.append(SRAND.nextAlphabetic(5, 30)).append(".txt");
        InputStream fileStream = new ByteArrayInputStream(
                note.getBytes(StandardCharsets.UTF_8));
        ZipEntry fileEntry = new ZipEntry(fileName.toString());
        return Map.entry(fileEntry, fileStream);
    }

