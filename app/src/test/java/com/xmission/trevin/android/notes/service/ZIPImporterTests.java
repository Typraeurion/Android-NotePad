    /**
     * Generate a metadata XML file from a set of test metadata.
     *
     * @param metadata the metadata to write to XML
     *
     * @return an InputStream on the buffered XML document
     */
    private static InputStream getMetadataXML(List<NoteMetadata> metadata) {
        ByteArrayOutputStream bs = new ByteArrayOutputStream();
        PrintStream out = new PrintStream(bs);
        out.println("<?xml version=\"1.0\" encoding=\"utf-8\"?>");
        out.printf(Locale.US, "<%s %s=\"%d\">\n",
                METADATA_TAG, ATTR_COUNT, metadata.size());
        for (NoteMetadata metadatum : metadata) {
            String value64 = (metadatum.getValue() == null) ? null
                    : encodeBase64(metadatum.getValue());
            out.printf(Locale.US, "  <%s %s=\"%d\" %s=\"%s\"",
                    METADATA_ITEM, ATTR_ID, metadatum.getId(), ATTR_NAME,
                    escapeXML(metadatum.getName()));
            if (value64 != null)
                out.printf(Locale.US, ">%s</%s>\n", value64, METADATA_ITEM);
            else
                out.printf(Locale.US, "/>\n");
        }
        out.printf(Locale.US, "</%s>\n", METADATA_TAG);
        out.close();
        return new ByteArrayInputStream(bs.toByteArray());
    }

