    /**
     * Generate a temporary ZIP file for testing the import.
     * This uses Java&rsquo;s built-in ZIP methods to ensure that
     * the Zip4j reader is compatible with files generated by
     * other applications.  However, it <i>cannot</i> handle
     * encrypted entries using standard ZIP encryption methods.
     *
     * @param tag a label to include in the temporary file name
     * identifying which test is generating it.
     * @param includeComment whether to add a file-level JSON comment
     * in the ZIP file.  This will generate the standard key/value pairs
     * used by {@link ZIPExporter}.
     * @param directories ZIP entries for any directories to add to the
     * ZIP file.  These will always be added first.
     * @param files pairs of ZIP entries and input streams for files
     * to add to the ZIP file.
     *
     * @return the temporary file
     *
     * @throws IOException if there was an error writing the ZIP file
     * @throws JSONException if we made a mistake creating the JSON comment
     */
    private static File createTestZip(
            String tag, boolean includeComment,
            List<ZipEntry> directories,
            List<Map.Entry<ZipEntry, InputStream>> files)
            throws IOException, JSONException {
        File tempFile = File.createTempFile("notes-" + tag + "-", ".zip");
        tempFile.deleteOnExit();
        try (FileOutputStream oStream = new FileOutputStream(tempFile);
             ZipOutputStream out = new ZipOutputStream(oStream)) {
            if (includeComment) {
                JSONObject comment = new JSONObject();
                comment.put(ATTR_VERSION, 2);
                comment.put(ATTR_DB_VERSION,
                        NoteRepositoryImpl.DATABASE_VERSION);
                comment.put(ATTR_EXPORTED, Instant.now()
                        .atOffset(ZoneOffset.UTC)
                        .format(DateTimeFormatter.ISO_INSTANT));
                comment.put(ATTR_TOTAL_RECORDS,
                        directories.size() + files.size());
                out.setComment(comment.toString());
            }
            for (ZipEntry entry : directories) {
                out.putNextEntry(entry);
                out.closeEntry();
            }
            for (Map.Entry<ZipEntry, InputStream> file : files) {
                out.putNextEntry(file.getKey());
                byte[] buffer = new byte[8192];
                int len;
                while ((len = file.getValue().read(buffer)) > 0)
                    out.write(buffer, 0, len);
                file.getValue().close();
                out.closeEntry();
            }
        }
        return tempFile;
    }

    /**
     * Generate an entry for a category directory in a ZIP file.  The
     * directory name is created from the category name simply by
     * stripping any trailing periods and appending the file separator.
     *
     * @param category the category whose directory to create
     *
     * @return the ZIP entry
     *
     * @throws JSONException if we made a mistake creating the JSON comment
     */
    private static ZipEntry makeCategoryDirectory(NoteCategory category)
            throws JSONException {
        JSONObject comment = new JSONObject();
        comment.put(ATTR_ID, category.getId());
        comment.put(ATTR_NAME, category.getName());
        String dirName = category.getName().replaceAll("\\.+$", "")
                + File.separator;
        ZipEntry dirEntry = new ZipEntry(dirName);
        dirEntry.setComment(comment.toString());
        return dirEntry;
    }

    /**
     * Generate an entry for a note from NotePad.
     *
     * @param note the note to create.  This note <i>must not</i> be
     * modified before the ZIP file is created.  If the note is encrypted,
     * this will assume we are writing the raw encrypted note to the ZIP
     * file; <i>no dot use this method</i> if we need to use ZIP encryption.
     * If the note is in any category other than &ldquo;Unfiled&rdquo;,
     * its {@code categoryName} field <b>must</b> be set.
     *
     * @return a {@link Map.Entry} with the ZIP entry and input stream for
     * the note content.
     *
     * @throws JSONException if we made a mistake creating the JSON comment
     */
    private static Map.Entry<ZipEntry,InputStream> makeNoteFile(
            NoteItem note) throws JSONException {
        JSONObject comment = new JSONObject();
        comment.put(ATTR_ID, note.getId());
        comment.put(NOTE_CREATED, note.getCreateTime().toString());
        comment.put(NOTE_MODIFIED, note.getModTime().toString());
        if (note.isPrivate()) {
            comment.put(ATTR_PRIVATE, true);
            if (note.isEncrypted())
                comment.put(ATTR_ENCRYPTION, note.getPrivate());
        }
        StringBuilder fileName = new StringBuilder();
        if (note.getCategoryId() != NoteCategory.UNFILED) {
            fileName.append(note.getCategoryName()
                    .replaceAll("\\.+$", ""));
            fileName.append(File.separator);
        }
        fileName.append(note.getId());
        InputStream fileStream;
        if (note.isEncrypted()) {
            fileName.append(" - Locked.aes");
            fileStream = new ByteArrayInputStream(note.getEncryptedNote());
        } else {
            String title = note.getNote();
            if (title.length() > 40)
                title = title.substring(0, 40);
            if (title.contains("\n"))
                title = title.substring(0, title.indexOf('\n'));
            if (title.contains("."))
                title = title.substring(0, title.indexOf('.'));
            fileName.append(" - ").append(title).append(".txt");
            fileStream = new ByteArrayInputStream(note.getNote()
                    .getBytes(StandardCharsets.UTF_8));
        }
        ZipEntry fileEntry = new ZipEntry(fileName.toString());
        fileEntry.setComment(comment.toString());
        return Map.entry(fileEntry, fileStream);
    }

    /**
     * Run the importer for a given test file.  The operation is expected
     * to run successfully.
     *
     * @param zipFile the ZIP file to import
     * @param importType the type of import to perform.
     * @param importPrivate whether to include private records.
     * @param zipPassword the password with which the ZIP file was
     * exporter, or {@code null}
     *
     * @return the progress indicator at the end of the import
     *
     * @throws IOException if there was an error reading the import file.
     * @throws RuntimeException if the import failed.
     */
    private MockProgressBar runImporter(
            File zipFile, ImportType importType,
            boolean importPrivate, char[] zipPassword)
        throws IOException {
        char[] currentPassword = null;
        if (globalEncryption.hasKey())
            currentPassword = Arrays.copyOf(globalEncryption.getPassword(),
                    globalEncryption.getPassword().length);
        assertTrue(String.format("Import test file %s does not exist",
                zipFile.getAbsolutePath()), zipFile.exists());
        MockProgressBar progress = new MockProgressBar();
        ZIPImporter importer = new ZIPImporter(mockPrefs, mockRepo,
                progress);
        importer.importData(zipFile.getName(), zipFile, importType,
                importPrivate, zipPassword, currentPassword);
        progress.setEndTime();
        return progress;
    }

