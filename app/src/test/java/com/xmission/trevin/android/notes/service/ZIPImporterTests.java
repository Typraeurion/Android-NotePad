    /**
     * Create a ZIP file containing just the metadata for a password hash.
     * This is used by several password check tests.
     *
     * @param password the password to hash and store in the ZIP file
     *
     * @return the generated ZIP file
     */
    private File makePasswordProtectedZIP(char[] password)
            throws IOException, JSONException {
        StringEncryption se = new StringEncryption();
        se.setPassword(password);
        se.addSalt();
        se.storePassword(mockRepo);
        NoteMetadata hash = mockRepo.getMetadataByName(
                StringEncryption.METADATA_PASSWORD_HASH);
        InputStream metaContent = getMetadataXML(
                Collections.singletonList(hash));
        return createTestZip("bundledPassword", true,
                Collections.singletonList(new ZipEntry(METADATA_DIR)),
                Collections.singletonList(Map.entry(
                        new ZipEntry(METADATA_FILE), metaContent)));
    }

